
public class TraversalCorrectnessTest {

    private static int passed = 0;
    private static int failed = 0;

    private static void check(String name, boolean condition) {

        if (condition) {
            System.out.println("[PASS] " + name);
            passed++;
        } else {
            System.out.println("[FAIL] " + name);
            failed++;
        }
    }

    private static boolean closeEnough(
            double actual, double expected) {

        double tolerance = Math.max(
            0.000001, Math.abs(expected) * 1e-10
        );

        return Math.abs(actual - expected) <= tolerance;
    }

    private static void testMatrix(
            String name, double[][] matrix, double expected) {

        double rowResult = RowMajorTraversal.sum(matrix);
        double columnResult = ColumnMajorTraversal.sum(matrix);

        check(name + " - Row-major sum",
            closeEnough(rowResult, expected));

        check(name + " - Column-major sum",
            closeEnough(columnResult, expected));
    }

    public static void main(String[] args) {

        System.out.println(
            "===== Matrix Traversal Correctness Tests ====="
        );

        System.out.println(
            "Student: Sultan Majeed | Reg ID: 247187"
        );

        // Test 1: Single element
        testMatrix(
            "Single element",
            new double[][]{{42.0}},
            42.0
        );

        // Test 2: Rectangular matrix (2 x 3)
        testMatrix(
            "Two rows and three columns",
            new double[][]{
                {1, 2, 3},
                {4, 5, 6}
            },
            21.0
        );

        // Test 3: Rectangular matrix (3 x 2)
        testMatrix(
            "Three rows and two columns",
            new double[][]{
                {1, 2},
                {3, 4},
                {5, 6}
            },
            21.0
        );

        // Test 4: Negative values
        testMatrix(
            "Negative matrix values",
            new double[][]{
                {-10, -20},
                {-30, -40}
            },
            -100.0
        );

        // Test 5: Zero values
        testMatrix(
            "Zero matrix values",
            new double[][]{
                {0, 0, 0},
                {0, 0, 0}
            },
            0.0
        );

        // Test 6: Matrix generated by MatrixData
        double[][] generated = MatrixData.createMatrix(10, 10);

        testMatrix(
            "Generated 10x10 matrix",
            generated,
            550.0
        );

        System.out.println("\n===== Test Summary =====");

        System.out.println("Passed: " + passed);
        System.out.println("Failed: " + failed);

        if (failed > 0) {
            throw new AssertionError(
                "Matrix traversal correctness tests failed."
            );
        }

        System.out.println("RESULT: ALL TESTS PASSED");
    }
}
